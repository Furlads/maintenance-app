export const FURLADS_QUOTE_PRICING_RULES = `
FURLADS QUOTE PRICING RULES

CORE PRINCIPLE
Price the whole job, not the measurement alone.

For every quote consider:
- materials
- labour
- plant / machinery
- waste disposal
- deliveries
- specialist / subcontractor costs
- access and handling
- contingency / risk

Base square-metre and linear-metre rates are benchmarks only. They must never be used as the final quote calculation on their own.

CALIBRATION PRINCIPLE - DO NOT DOUBLE COUNT DIFFICULTY
Complexity rules exist to improve realism, not to stack surcharges on top of the same problem.

For each difficulty, identify the actual cost effect once and price that effect once.
Examples:
- Poor access usually increases labour time, handling, protection and sometimes waste movement. If those extra man-days and handling costs have already been added, do NOT also add a blanket access percentage to the whole package.
- A retaining wall is priced as its own structural item. Do NOT also apply a large patio complexity surcharge simply because the wall creates the level change, unless there is genuinely extra patio labour such as steps, awkward cuts or drainage interfaces.
- Multiple deck areas may add extra labour/cuts. Do NOT inflate both the decking m2 rate and then apply another full complexity multiplier for the same layout.
- A contingency allowance is for genuine uncertainty. Do NOT use contingency to repeat costs already allowed for in labour, plant, waste or materials.

Prefer explicit cost additions over broad multipliers.
Use a multiplier only where the affected cost cannot reasonably be itemised.
Never apply more than one uplift for the same underlying difficulty.

INTERNAL SELLING-PRICE FORMULA
Direct Job Cost = all expected job costs before gross profit.
Selling Price = Direct Job Cost / (1 - desired gross margin).

Default minimum gross margin: 30%.
Always calculate and show internal selling-price references at:
- 30% GP
- 35% GP
- 40% GP

Never recommend below 30% GP without a clear warning.

HARD COST DISCIPLINE
Estimated hard costs must be actual expected costs to Furlads, NOT customer selling allowances and NOT benchmark selling rates.
Hard costs should contain the real expected spend on materials, labour, plant, disposal, deliveries, subcontractors and directly attributable logistics.
Do not put profit, margin, benchmark selling rates or arbitrary percentage uplifts into estimated hard costs.

Before accepting a hard-cost estimate, sanity check each major category against the physical quantities and likely crew time.
If hard costs appear unusually high, review them before using the 30% margin protection because an inflated hard-cost estimate will mechanically create an inflated quote.

LABOUR
Calculate labour in man-days.
workers x working days = man-days.
Use the true cost of the actual workers where known.
For employed workers include employment burden where available.
For subcontractors use the real agreed day rate.

Labour duration should be built from the work sequence first, then adjusted for site conditions.
Do not start with a normal duration, multiply it for access, and then add separate access days again.
Choose one method: either explicit extra man-days or a labour multiplier, not both for the same issue.

ACCESS / PRODUCTIVITY
Start from normal productivity, then adjust labour for access and handling.
- Standard access: 1.00 labour multiplier
- Moderate restricted access: typically 1.05-1.15
- Difficult access: typically 1.10-1.25
- Very difficult / through-house access: typically 1.15-1.35

These are guidance ranges, not automatic multipliers.
Use the lowest realistic adjustment when the work can still be carried efficiently with barrows/trolleys and a short route.
Use the upper end only where repeated manual carrying, steps, long distances, fragile internal routes or severe restrictions materially slow the crew.

Do not increase material purchase prices just because access is poor. Increase only the genuinely affected handling labour, protection, duration and relevant breakage/risk allowance.

Automatic access flags:
- under 900mm: restricted
- under 750mm: severely restricted
- under 700mm: very difficult
- through house: property protection + extra handling + reduced productivity

An access flag requires a review; it does NOT automatically justify applying the maximum multiplier.

WORK-SPECIFIC RULES
Porcelain:
- £170/m2 ex VAT is a straightforward customer selling benchmark for a standard complete installation, not a hard-cost rate and not an automatic quote formula.
- For normal domestic work, the effective customer selling price for the horizontal porcelain element will commonly remain around £160-£220/m2 before separately priced structural walls, major demolition, specialist drainage or exceptional site constraints.
- If the effective horizontal porcelain price exceeds about £240/m2, stop and manually review for double counting unless there is clear evidence of major breakout, drainage, structural work or unusually severe logistics.
- separately consider removal, levels, steps, cuts, drainage, retaining structures and restricted access.
- vertical porcelain facing has different productivity from floor laying.
- access uplifts should usually be represented by realistic extra labour/handling, not a blanket percentage applied to the full porcelain selling value.

Existing patio removal:
Assess separately from installation. Distinguish loose/dry-bed, mortar-laid and heavy concrete/reinforced breakout.
Do not charge both a full demolition package and another broad paving complexity uplift for the same breakout work.

Walls:
Classify decorative, low retaining or significant/structural retaining before pricing.
Retaining walls require foundation, drainage, backfill and added labour/risk allowances.
Price the wall as a complete wall package from expected material + labour + foundation + facing costs.
Do not then repeat the wall cost inside the patio complexity allowance.

Composite decking:
Include removal, waste, new subframe unless inspected and confirmed sound, boards, clips/fixings, trims, steps, edge detailing and labour.
Multiple separate areas are slower than one rectangle of equal area, but represent that primarily through extra labour/cutting rather than stacking percentage multipliers.
For a straightforward domestic composite replacement with a new standard subframe, sense-check any unusually high per-m2 selling price against actual material specification and man-days before accepting it.

Turf / seed:
Include removal, ground preparation, levelling, topsoil where needed, labour, waste and access.
Do not price purely by m2.

Gravel / gravel-grid driveways:
Include excavation, membrane, sub-base where required, grids where required, decorative gravel, edging, plant, labour and waste.

Fencing:
Price from bays/specification, posts, gravel boards, postcrete, gates, removal, waste, access, difficult digging and cuts. Do not rely on linear metres alone.

Sleepers:
Consider sleeper count/type, height, posts/stakes, fixings, excavation, backfill, retained pressure, waste and labour.

EXCAVATION / WASTE
Calculate excavation from area x average depth = m3, then allow for bulking/expansion.
Estimate likely disposal loads from volume and material type.
Never assume one grab load without calculating likely volume first.
If waste must be double-handled, add handling labour.
Do not inflate the grab-lorry supplier charge because access is poor; poor access affects the labour to get spoil to the grab, not the grab company's base disposal price.

PLANT
Consider whether the site physically allows suitable digger, dumper, breaker, saw, compactor, mixer, stump grinder or rotavator.
No digger access means more labour; it does not mean the same job with the digger cost simply removed.
Again, add the realistic replacement labour once; do not combine a no-machine labour addition with another full access multiplier if both describe the same lost productivity.

DRAINAGE
For patios check falls, DPC relationship, existing drains, channels, soakaway need, level changes and retaining-wall drainage.
Price specialist drainage or clearly identify it as an unresolved item.

MATERIAL WASTE ALLOWANCES
Use sensible ordering waste allowances, typically:
- porcelain 10%, rising to 12-15% for complex cuts / multiple areas / steps / cladding / narrow paths
- turf about 5%
- composite decking about 5-10%
- blocks about 5%

COMBINED JOBS
Each standalone package includes its fair share of mobilisation, deliveries, waste, setup, protection, travel and plant mobilisation.
When packages are completed together, reduce only the duplicated costs actually saved.
Never apply an arbitrary package discount.

A combined package should normally show a meaningful but credible saving when several standalone packages genuinely duplicate setup, protection, delivery or mobilisation.
If the calculated saving is only a token amount (for example a few pounds on a multi-thousand-pound job), review the package logic because duplicated standalone costs have probably not been modelled correctly.
Do not force a discount where there is no real duplication, but do not claim efficiencies while showing effectively no saving.

CONTINGENCY
Suggested internal contingency:
- straightforward: 2-3%
- moderate complexity: 3-5%
- high complexity / restricted access: 5-7%
- significant unknown ground / structural conditions: 7-10%

Contingency applies to genuine unknowns and residual risk only.
Reduce or omit contingency on cost items that are already well defined and fully priced.
Do not use contingency as another general complexity surcharge.

UNKNOWN CONDITIONS
Never ignore significant unknowns. Either:
A. include contingency,
B. use a clearly labelled provisional allowance, or
C. exclude it clearly and require approval before extra work.

COMPLEXITY
Complexity is primarily a prompt to adjust the affected labour/task assumptions, not a universal price multiplier.

Low: normal task productivity.
Medium: modest explicit extra labour/handling where justified.
High: clearly itemised extra labour/logistics and a review of programme.
Very high: manual review before quote is issued.

Do NOT apply a generic complexity multiplier on top of already-adjusted labour unless the multiplier replaces, rather than duplicates, explicit additions.

AUTOMATIC WARNING FLAGS
Warn/review if any apply:
- access below 700mm
- access through house
- retaining wall supporting patio
- more than 500mm level difference
- large concrete breakout
- digger cannot access
- unknown drainage on large paved area
- deck subframe condition unknown
- more than 10 tonnes estimated excavation
- selling price below 30% GP
- labour estimate inconsistent with scope
- customer-supplied material specification unknown
- horizontal porcelain effective selling rate above £240/m2 without exceptional scope
- access/complexity appears to have been charged in more than one way
- combined-package saving is negligible despite claimed duplicated-cost efficiencies

LABOUR SANITY CHECK
Compare total scope against total man-days before accepting the programme.
Build a task-level programme first: strip-out, excavation/base, walling, paving, decking, finishing.
Then consider which tasks overlap and which genuinely require the full crew.
If the programme is aggressive, use a safer realistic duration.
If the programme is conservative, do not inflate it merely because several complexity flags exist.

PRICE SANITY CHECK
After margin calculation, compare the proposed selling price with the physical scope and benchmark ranges.
A margin formula is a floor/protection mechanism, not proof that the underlying hard-cost estimate is correct.
If the recommended quote moves dramatically after adding site-complexity rules, inspect the hard-cost categories for duplicated labour, duplicated mobilisation, duplicated waste or duplicated risk.

When a quote differs by more than roughly 15-20% from the initial benchmark-based sense check, explain internally what specific real costs justify the difference.
If there is no specific cost explanation, recalculate rather than accepting the higher figure.

INTERNAL QUOTE OUTPUT
Show internally where information supports it:
- measurements: m2 / linear metres / m3
- expected materials cost
- expected labour: man-days and cost
- plant
- waste
- logistics / access
- contingency
- estimated total job cost
- selling price at 30% GP
- selling price at 35% GP
- selling price at 40% GP
- effective selling rate for major measured work (for example paving £/m2) as a sanity check
- recommended customer price ex VAT

CUSTOMER OUTPUT
Do not expose internal costing unless requested. Normally show clear works, measurements, materials/finish, preparation included, waste included, important assumptions, price ex VAT, VAT and total inc VAT.

QUESTION BEHAVIOUR
Do not turn the site visit into a giant questionnaire.
Use the written description, measurements, photos and notes first.
Only stop to ask a question when the missing answer could materially change price, programme or safe specification.
When possible, make a sensible provisional assumption and label it clearly instead of blocking the quote.

Before recommending a price, ask internally:
1. What will actually make this job take longer or cost more than the measurements suggest?
2. Have I already charged for that difficulty somewhere else?
3. Are estimated hard costs real Furlads costs rather than selling allowances?
4. Does the final effective rate still make sense against the physical job?
`;

export function sellingPriceForMargin(jobCost: number, margin: number) {
  if (!Number.isFinite(jobCost) || jobCost < 0) return 0;
  if (!Number.isFinite(margin) || margin <= 0 || margin >= 1) return 0;
  return Number((jobCost / (1 - margin)).toFixed(2));
}

export function grossMarginPercent(price: number, jobCost: number) {
  if (!Number.isFinite(price) || price <= 0 || !Number.isFinite(jobCost) || jobCost < 0) return 0;
  return Number((((price - jobCost) / price) * 100).toFixed(1));
}
